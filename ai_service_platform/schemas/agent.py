from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field

from ai_service_platform.schemas.common import BaseLLMUsage


class ToolCallRecord(BaseModel):
    tool_name: str = Field(..., description="Name of the tool invoked by the agent.")
    tool_args: Dict[str, Any] = Field(default_factory=dict, description="Arguments passed to the tool.")
    tool_output: Any = Field(..., description="Output or error returned by the tool.")
    status: str = Field("success", description="Status of tool execution: 'success' or 'error'.")


class AgentRunRequest(BaseModel):
    thread_id: Optional[str] = Field(
        default=None,
        description="Unique conversation session ID for multi-turn short-term memory. Auto-generated if omitted."
    )
    prompt: str = Field(..., min_length=2, description="Goal or instruction for the LangGraph agent.")
    system_prompt: Optional[str] = Field(
        default=None, 
        description="Optional custom system persona/instructions for the agent."
    )
    max_iterations: int = Field(
        default=5, 
        ge=1, 
        le=10, 
        description="Infinite loop guard: max tool-calling iterations allowed."
    )


class AgentRunResponse(BaseLLMUsage):
    """Standardized response model for autonomous LangGraph agent runs."""
    thread_id: str = Field(..., description="Conversation thread ID used for persisting state.")
    final_answer: str = Field(..., description="Final synthesized response from the agent.")
    tool_calls: List[ToolCallRecord] = Field(
        default_factory=list, 
        description="Chronological record of all tool calls executed during the reasoning loop."
    )
    iterations: int = Field(..., description="Number of agent reasoning cycles executed in the current turn.")
    messages_count: int = Field(..., description="Cumulative total number of messages retained across the entire thread's history so far.")


class ThreadMessageRecord(BaseModel):
    role: str = Field(..., description="Role of the message sender: 'system', 'human', 'ai', or 'tool'.")
    content: str = Field(..., description="Text content of the message.")
    tool_calls: Optional[List[Dict[str, Any]]] = Field(default=None, description="Tool calls generated by an AI message.")
    tool_call_id: Optional[str] = Field(default=None, description="Tool call reference ID for tool outputs.")
    name: Optional[str] = Field(default=None, description="Tool name for tool output messages.")


class ThreadHistoryResponse(BaseModel):
    thread_id: str = Field(..., description="Conversation thread ID.")
    messages: List[ThreadMessageRecord] = Field(default_factory=list, description="Chronological message history in short-term state.")
    total_messages: int = Field(..., description="Total count of messages stored in the thread's checkpoint.")
    accumulated_tokens: Dict[str, int] = Field(default_factory=dict, description="Cumulative token usage across all turns in this thread.")
    accumulated_cost: float = Field(0.0, description="Cumulative monetary cost in USD across all turns in this thread.")


class ThreadClearResponse(BaseModel):
    thread_id: str = Field(..., description="Conversation thread ID that was cleared.")
    cleared: bool = Field(True, description="Whether the thread memory was successfully cleared.")
    message: str = Field(..., description="Status summary.")
